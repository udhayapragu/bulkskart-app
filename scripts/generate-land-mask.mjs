// Builds src/data/landMask.ts: a 0.5 degree land/ocean mask used by the hero globe.
//
// Source: Natural Earth 1:110m land polygons (public domain), as packaged in the "world-atlas" npm
// package (ISC licence, Mike Bostock). It is only read here, at build time of the data file. Nothing
// from that package ships to the browser except the small mask this script writes.
//
// Run:  npm pack world-atlas@2.0.2   (in an empty folder, then extract package/land-110m.json)
//       node scripts/generate-land-mask.mjs path/to/land-110m.json
import { readFileSync, writeFileSync } from 'node:fs';

const WIDTH = 720; // columns, 0.5 degrees each, west to east from -180
const HEIGHT = 360; // rows, 0.5 degrees each, north to south from +90

const inputPath = process.argv[2];
if (!inputPath) {
  console.error('Usage: node scripts/generate-land-mask.mjs <land-110m.json>');
  process.exit(1);
}

const topology = JSON.parse(readFileSync(inputPath, 'utf8'));
const { scale, translate } = topology.transform;

// TopoJSON arcs are delta-encoded and quantised. Decode them to [lon, lat].
const arcs = topology.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ringFromArcIndexes(indexes) {
  const points = [];
  for (const index of indexes) {
    const arc = index >= 0 ? arcs[index] : arcs[~index].slice().reverse();
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

const rings = [];
for (const geometry of topology.objects.land.geometries) {
  const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.arcs;
  for (const polygon of polygons) {
    for (const ring of polygon) rings.push(ringFromArcIndexes(ring));
  }
}

// Scanline fill with the even-odd rule, so lakes and holes work without special cases.
const land = new Uint8Array(WIDTH * HEIGHT);
for (let row = 0; row < HEIGHT; row += 1) {
  const lat = 90 - ((row + 0.5) * 180) / HEIGHT;
  const crossings = [];
  for (const ring of rings) {
    for (let i = 0; i < ring.length - 1; i += 1) {
      const [lonA, latA] = ring[i];
      const [lonB, latB] = ring[i + 1];
      if (latA <= lat !== latB <= lat) {
        crossings.push(lonA + ((lat - latA) / (latB - latA)) * (lonB - lonA));
      }
    }
  }
  crossings.sort((a, b) => a - b);
  for (let k = 0; k + 1 < crossings.length; k += 2) {
    const first = Math.ceil(((crossings[k] + 180) * WIDTH) / 360 - 0.5);
    const last = Math.floor(((crossings[k + 1] + 180) * WIDTH) / 360 - 0.5);
    for (let col = Math.max(0, first); col <= Math.min(WIDTH - 1, last); col += 1) land[row * WIDTH + col] = 1;
  }
}

// Run-length encode each row: alternating ocean/land run lengths starting with ocean, as varints,
// preceded by the number of runs in that row.
const bytes = [];
const pushVarint = (value) => {
  let rest = value;
  while (rest >= 0x80) {
    bytes.push((rest & 0x7f) | 0x80);
    rest >>= 7;
  }
  bytes.push(rest);
};
for (let row = 0; row < HEIGHT; row += 1) {
  const runs = [];
  let current = 0;
  let length = 0;
  for (let col = 0; col < WIDTH; col += 1) {
    const value = land[row * WIDTH + col];
    if (value === current) {
      length += 1;
    } else {
      runs.push(length);
      current = value;
      length = 1;
    }
  }
  runs.push(length);
  pushVarint(runs.length);
  for (const run of runs) pushVarint(run);
}

const base64 = Buffer.from(bytes).toString('base64');
const lines = base64.match(/.{1,110}/g) ?? [];
const landCells = land.reduce((sum, value) => sum + value, 0);

const source = `// Generated by scripts/generate-land-mask.mjs. Do not edit by hand.
// Land mask from Natural Earth 1:110m land polygons (public domain), ${WIDTH} x ${HEIGHT} cells of 0.5 degrees.
// Rows run north to south from +90, columns west to east from -180. Each row is a run count followed by
// alternating ocean/land run lengths (ocean first), all as base-128 varints.
export const LAND_MASK_WIDTH = ${WIDTH};
export const LAND_MASK_HEIGHT = ${HEIGHT};
export const LAND_MASK_RLE =
${lines.map((line) => `  '${line}'`).join(' +\n')};
`;
writeFileSync(new URL('../src/data/landMask.ts', import.meta.url), source);

// Quick look at the result: one character per 6 x 6 cells.
const preview = [];
for (let row = 0; row < HEIGHT; row += 12) {
  let text = '';
  for (let col = 0; col < WIDTH; col += 6) {
    let sum = 0;
    for (let dy = 0; dy < 12; dy += 1) for (let dx = 0; dx < 6; dx += 1) sum += land[(row + dy) * WIDTH + col + dx];
    text += sum > 36 ? '#' : sum > 10 ? '+' : sum > 0 ? '.' : ' ';
  }
  preview.push(text);
}
console.log(preview.join('\n'));
console.log(`\nland cells: ${landCells} of ${WIDTH * HEIGHT} (${((100 * landCells) / (WIDTH * HEIGHT)).toFixed(1)}%)`);
console.log(`encoded: ${bytes.length} bytes, base64 ${base64.length} chars`);
