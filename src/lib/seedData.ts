/**
 * The project's database migrations ship demonstration records: companies, products and tens of
 * thousands of RFQs that were generated for the template, not submitted by real businesses.
 * The public landing page must never present them as real suppliers or live buyer demand.
 *
 * Everything here is derived from the migrations themselves:
 *  - supabase/migrations/00005_seed_60_companies.sql and 00035_seed_worldwide_companies.sql give every
 *    demo company the placeholder owner below. Real suppliers have a real signed-up user as owner.
 *  - supabase/migrations/00015_seed_india_requirements_50k.sql generates RFQs titled
 *    "<product> - Lot #5xxxx" with one fixed boilerplate description.
 *
 * Nothing is deleted. These rows are only left out of landing page queries. To show them anyway (for
 * example to preview the layout against demo data), build with VITE_INCLUDE_TEMPLATE_SEED_DATA=true.
 */

/** Owner id given to every demo company by the seed migrations. */
export const SEED_OWNER_ID = '00000000-0000-0000-0000-000000000001';

/** Demo companies from 00035 use ids that start like this. */
const SEED_COMPANY_ID_PREFIX = 'e1000001-0000-0000-0000-';

/** SQL LIKE pattern matching the titles generated by the RFQ seed. */
export const SEEDED_RFQ_TITLE_LIKE = '% - Lot #%';

const SEEDED_RFQ_TITLE = / - Lot #\d+\s*$/;
const SEEDED_RFQ_DESCRIPTION = /^Requirement from India\. Looking for verified manufacturers for bulk supply\./;

export const INCLUDE_TEMPLATE_SEED_DATA: boolean = import.meta.env.VITE_INCLUDE_TEMPLATE_SEED_DATA === 'true';

export function isSeededCompany(row: { id?: string | null; owner_id?: string | null }): boolean {
  if (INCLUDE_TEMPLATE_SEED_DATA) return false;
  return row.owner_id === SEED_OWNER_ID || (row.id ?? '').startsWith(SEED_COMPANY_ID_PREFIX);
}

export function isSeededRequirement(row: { title?: string | null; description?: string | null }): boolean {
  if (INCLUDE_TEMPLATE_SEED_DATA) return false;
  return SEEDED_RFQ_TITLE.test(row.title ?? '') || SEEDED_RFQ_DESCRIPTION.test(row.description ?? '');
}
